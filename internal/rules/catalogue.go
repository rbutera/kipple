// editorCacheRoots returns the four Chromium/Electron cache folders that
// VS Code and its forks keep under Application Support.
func editorCacheRoots(app string) []string {
	base := "Library/Application Support/" + app + "/"
	return []string{base + "Cache", base + "CachedData", base + "Code Cache", base + "GPUCache"}
}

func projectArtifact(id, title string, names, markers []string, what, ifRemoved string) Rule {
	return Rule{
		ID:    id,
		Title: title,
		Tier:  TierReview,
		Roots: DefaultProjectRoots(),
		Match: Match{Kind: MatchProjectArtifact, Names: names, Markers: markers},
		// Dependency installs: a venv ships certifi's cacert.pem.
		PackageCache: true,
		Conditions: Conditions{
			RequiresIdleProject:  true,
			IdleDays:             30,
			RequiresCleanGit:     true,
			SkipIfAgentInProject: true,
		},
		Owner:     Owner{Name: "Project build tools", Processes: AgentProcesses()},
		What:      what,
		IfRemoved: ifRemoved,
	}
}

